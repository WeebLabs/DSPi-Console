// Generates DSPi Console/VendorCommands.swift from Protocol/dspi_commands.json,
// the firmware's vendor command registry. Run from anywhere:
//
//   swift Tools/VendorProtocol/gen-vendor-commands.swift           (writes the file)
//   swift Tools/VendorProtocol/gen-vendor-commands.swift --check   (exit 1 if stale)
//
// The output is deterministic, so a stale or hand-edited file shows up as a
// diff. VendorCommandsTests checks the generated table against the JSON too.

import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data((message + "\n").utf8))
    exit(1)
}

let repo = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
let input = repo.appendingPathComponent("Protocol/dspi_commands.json")
let output = repo.appendingPathComponent("DSPi Console/VendorCommands.swift")
let checkOnly = CommandLine.arguments.dropFirst().contains("--check")

guard let data = try? Data(contentsOf: input),
      let root = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
      let proto = root["protocol"] as? [String: Any],
      let major = proto["major"] as? Int, let minor = proto["minor"] as? Int,
      let pages = root["pages"] as? [[String: Any]] else {
    fail("cannot read \(input.path)")
}

let knownFlags = ["USB_ONLY": "usbOnly", "SET_USB_ONLY": "setUsbOnly", "BULK": "bulk",
                  "DEFERRED": "deferred", "FLASH": "flash", "RESTART": "restart",
                  "KEEPALIVE": "keepalive"]
let knownAddr = ["NONE": "none", "CHANNEL": "channel", "INPUT": "input", "OUTPUT": "output",
                 "OUTPUT_ALL": "outputAll", "SLOT": "slot", "PIN_OUTPUT": "pinOutput",
                 "PRESET": "preset", "CH_BAND": "channelBand", "IN_OUT": "inputOutput",
                 "SOURCE": "source", "SPDIF_RX": "spdifRx", "I2S_PAIR": "i2sPair", "ROLE": "role",
                 "CS_SLOT": "csSlot", "CS_SLOT_TYPE": "csSlotType", "CS_SUB": "csSub", "CS_GROUP": "csGroup",
                 "CS_MACRO": "csMacro", "CS_MACRO_STEP": "csMacroStep", "CS_PAGE": "csPage",
                 "CS_NOUN": "csNoun", "PAGE": "page", "PAGE_CMD": "pageCommand",
                 "OFFSET": "offset", "INDEX": "index"]

func hex(_ v: Int, _ digits: Int) -> String {
    "0x" + String(String(v, radix: 16, uppercase: true).reversed())
        .padding(toLength: digits, withPad: "0", startingAt: 0).reversed()
}

// Project rule: no em-dashes in comments.
func docText(_ s: String) -> String {
    s.replacingOccurrences(of: "\u{2014}", with: "-")
     .trimmingCharacters(in: .whitespacesAndNewlines)
}

var out = """
// GENERATED by Tools/VendorProtocol/gen-vendor-commands.swift from
// Protocol/dspi_commands.json. Do not edit: update the registry and run the
// generator again. VendorCommandsTests fails when the two disagree.

import Foundation

/// Paged protocol version this registry describes. The probe accepts a device
/// whose SYS.PROTOCOL_INFO major equals `major`.
enum VendorProtocolVersion {
    static let major: UInt8 = \(major)
    static let minor: UInt8 = \(minor)
}

/// Every command, as `VC.PAGE.NAME`.
enum VC {

"""

var table: [String] = []
var pageTable: [String] = []
var seenIDs = Set<Int>()

for page in pages {
    guard let number = page["page"] as? Int, let pname = page["mnemonic"] as? String,
          let revision = page["revision"] as? Int,
          let commands = page["commands"] as? [[String: Any]] else {
        fail("malformed page entry")
    }
    pageTable.append("        VendorPageInfo(number: \(hex(number, 2)), name: \"\(pname)\", revision: \(revision)),")
    if let doc = page["doc"] as? String { out += "    /// \(docText(doc)).\n" }
    out += "    enum \(pname) {\n"
    out += "        static let page: UInt8 = \(hex(number, 2))\n"
    for c in commands {
        guard let cmd = c["cmd"] as? Int, let name = c["name"] as? String,
              let id = c["id"] as? Int, let hasGet = c["get"] as? Bool,
              let hasSet = c["set"] as? Bool, let addr = c["addr"] as? String,
              let setMin = c["set_min"] as? Int, let setMax = c["set_max"] as? Int,
              let flags = c["flags"] as? [String] else {
            fail("malformed command in page \(pname)")
        }
        guard id == (number << 8) | cmd else { fail("\(pname).\(name): id does not match page and command") }
        guard seenIDs.insert(id).inserted else { fail("\(pname).\(name): duplicate id") }
        guard let addrCase = knownAddr[addr] else { fail("\(pname).\(name): unknown address kind \(addr)") }
        let flagCases = flags.map { f -> String in
            guard let k = knownFlags[f] else { fail("\(pname).\(name): unknown flag \(f)") }
            return "." + k
        }
        let getLen: String
        switch c["get_len"] {
        case let n as Int: getLen = ".fixed(\(n))"
        case let s as String where s == "var": getLen = ".variable"
        case nil, is NSNull: getLen = ".none"
        default: fail("\(pname).\(name): unexpected get_len")
        }
        guard hasGet == (getLen != ".none") else { fail("\(pname).\(name): get flag and get_len disagree") }
        let build = (c["build"] as? String).map { "\"\($0)\"" } ?? "nil"

        var dirs: [String] = []
        if hasGet { dirs.append("GET") }
        if hasSet { dirs.append("SET") }
        if let doc = c["doc"] as? String {
            out += "        /// \(docText(doc)). \(dirs.joined(separator: " and "))"
            if let b = c["build"] as? String { out += ", \(b) builds only" }
            out += ".\n"
        }
        out += "        static let \(name) = VendorCommand(\(hex(id, 4)))\n"

        table.append("""
                VendorCommandInfo(command: VC.\(pname).\(name), pageName: "\(pname)", name: "\(name)",
                                  hasGet: \(hasGet), hasSet: \(hasSet), address: .\(addrCase),
                                  getLength: \(getLen), setMin: \(setMin), setMax: \(setMax),
                                  flags: [\(flagCases.joined(separator: ", "))], build: \(build)),
        """)
    }
    out += "    }\n\n"
}
out.removeLast()   // one blank line before the closing brace is enough
out += "}\n\n"
out += """
extension VendorCommandRegistry {
    static let pages: [VendorPageInfo] = [
\(pageTable.joined(separator: "\n"))
    ]

    /// Every command in registry order.
    static let all: [VendorCommandInfo] = [
\(table.joined(separator: "\n"))
    ]
}

"""

let existing = try? String(contentsOf: output, encoding: .utf8)
if checkOnly {
    if existing == out { exit(0) }
    fail("\(output.path) is stale: run swift Tools/VendorProtocol/gen-vendor-commands.swift")
}
if existing != out {
    do { try out.write(to: output, atomically: true, encoding: .utf8) } catch { fail("write failed: \(error)") }
    print("wrote \(output.path): \(table.count) commands on \(pageTable.count) pages")
} else {
    print("\(output.path) is up to date")
}
